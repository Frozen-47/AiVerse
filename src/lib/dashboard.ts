export async function fetchDashboardStats(): Promise<DashboardStats> {
  let totalEntries = 766;
  let totalUsers = 10;
  let averageRating = 4.38;
  let totalRatings = 8;
  let activeToday = 0;
  let activeThisWeek = 2;
  let newEntriesCount = 504;

  try {
    // 1. Fetch catalog stats from public JSON generated by pulse if available
    try {
      const res = await fetch("/data/catalog_stats.json", { cache: "no-cache" });
      if (res.ok) {
        const catStats = (await res.json()) as CatalogStatsJson;
        if (typeof catStats.totalEntries === "number" && catStats.totalEntries > 0) {
          totalEntries = catStats.totalEntries;
        }
        if (typeof catStats.newEntriesCount === "number" && catStats.newEntriesCount >= 0) {
          newEntriesCount = catStats.newEntriesCount;
        }
        if (typeof catStats.totalUsers === "number" && catStats.totalUsers > 0) {
          totalUsers = catStats.totalUsers;
        }
        if (typeof catStats.averageRating === "number" && catStats.averageRating > 0) {
          averageRating = catStats.averageRating;
        }
        if (typeof catStats.totalRatings === "number" && catStats.totalRatings > 0) {
          totalRatings = catStats.totalRatings;
        }
      }
    } catch {
      // Ignore network / offline fallback
    }

    // 2. Query Supabase for approved entries count
    const { count: entriesCount, error: entriesError } = await supabase
      .from("entries")
      .select("*", { count: "exact", head: true })
      .eq("approved", true);

    if (!entriesError && entriesCount !== null && entriesCount > 0) {
      totalEntries = Math.max(totalEntries, entriesCount);
    }

    // 3. Query Supabase for actual registered user profiles & activity timestamps
    const { data: usersData, count: usersCount, error: usersError } = await supabase
      .from("user_preferences")
      .select("updated_at", { count: "exact" });

    if (!usersError && usersCount !== null && usersCount > 0) {
      totalUsers = usersCount;
    } else if (usersData && usersData.length > 0) {
      totalUsers = usersData.length;
    }

    if (usersData && usersData.length > 0) {
      const now = Date.now();
      const oneDayMs = 24 * 60 * 60 * 1000;
      const sevenDaysMs = 7 * oneDayMs;
      let todayCount = 0;
      let weekCount = 0;

      for (const u of usersData) {
        if (u.updated_at) {
          const diff = now - new Date(u.updated_at).getTime();
          if (diff >= 0 && diff <= oneDayMs) {
            todayCount++;
          }
          if (diff >= 0 && diff <= sevenDaysMs) {
            weekCount++;
          }
        }
      }
      activeToday = todayCount;
      activeThisWeek = weekCount;
    }

    // 4. Query Supabase for actual community ratings
    const { data: ratingsData, error: ratingsError } = await supabase
      .from("entry_ratings")
      .select("rating");

    if (!ratingsError && ratingsData && ratingsData.length > 0) {
      totalRatings = ratingsData.length;
      const validRatings = ratingsData
        .map((r) => Number(r.rating))
        .filter((val) => !isNaN(val) && val >= 1 && val <= 5);

      if (validRatings.length > 0) {
        const sum = validRatings.reduce((acc, curr) => acc + curr, 0);
        averageRating = Math.round((sum / validRatings.length) * 100) / 100;
      }
    }
  } catch (err) {
    console.error("Error fetching dashboard stats:", err);
  }

  return {
    totalEntries,
    totalUsers,
    averageRating,
    totalRatings,
    activeToday,
    activeThisWeek,
    newEntriesCount,
  };
}

let radarBundleCache: Promise<DashboardRadarBundle> | null = null;

export async function fetchDashboardRadarBundle(): Promise<DashboardRadarBundle> {
  if (radarBundleCache) return radarBundleCache;

  radarBundleCache = (async () => {
    const safeFetchJson = async <T>(url: string): Promise<T | null> => {
      try {
        const res = await fetch(url, { cache: "no-cache" });
        if (!res.ok) return null;
        return (await res.json()) as T;
      } catch {
        return null;
      }
    };

    const [catalogStats, linksHealth, batches, logs] = await Promise.all([
      safeFetchJson<CatalogStatsJson>("/data/catalog_stats.json"),
      safeFetchJson<LinksHealthJson>("/data/links_health.json"),
      safeFetchJson<NewlyAddedBatch[]>("/data/newly_added_models.json"),
      safeFetchJson<RadarPipelineRun[]>("/data/github_action_logs.json"),
    ]);

    const recentBatches = Array.isArray(batches) ? batches.slice(0, 6) : [];
    const latestRun =
      Array.isArray(logs) && logs.length > 0
        ? logs.find((run) => run.workflow?.toLowerCase().includes("radar")) || logs[0]
        : null;

    return {
      catalogStats,
      linksHealth,
      recentBatches,
      latestRun,
    };
  })();

  return radarBundleCache;
}

export function computeTaxonomyBreakdown(entries: Entry[]): TaxonomySlice[] {
  const counts: Record<Entry["type"], number> = {
    Model: 0,
    Platform: 0,
    Dataset: 0,
    AI: 0,
    Framework: 0,
  };

  for (const e of entries) {
    if (e.type in counts) {
      counts[e.type]++;
    }
  }

  const total = entries.length || 1;
  return TAXONOMY_META.map((meta) => {
    const count = counts[meta.type];
    return {
      ...meta,
      count,
      pct: Math.round((count / total) * 100),
    };
  });
}

export function classifyLicenseBucket(license: string | undefined): LicenseBucketId {
  const lic = (license || "").trim().toLowerCase();
  if (!lic) return "other";

  if (
    lic.includes("mit") ||
    lic.includes("apache") ||
    lic.includes("bsd") ||
    lic.includes("gpl") ||
    lic.includes("cc0") ||
    lic.includes("wtfpl") ||
    lic.includes("public domain") ||
    lic.includes("open source")
  ) {
    return "open_source";
  }

  if (
    lic.includes("open weights") ||
    lic.includes("open data") ||
    lic === "open" ||
    lic.includes("llama") ||
    lic.includes("gemma") ||
    lic.includes("qwen") ||
    lic.includes("deepseek") ||
    lic.includes("openrail") ||
    lic.includes("open rail") ||
    lic.includes("openmdw") ||
    lic.includes("cc-by") ||
    lic.includes("cc by") ||
    lic.includes("odc") ||
    lic.includes("cdla") ||
    lic.includes("falcon") ||
    lic.includes("apple-amlr")
  ) {
    return "open_weights";
  }

  if (
    lic.includes("proprietary") ||
    lic.includes("commercial") ||
    lic.includes("freemium")
  ) {
    return "proprietary";
  }

  return "other";
}

export function computeLicenseMix(entries: Entry[]): LicenseBucketSlice[] {
  const counts: Record<LicenseBucketId, number> = {
    open_source: 0,
    open_weights: 0,
    proprietary: 0,
    other: 0,
  };

  for (const entry of entries) {
    counts[classifyLicenseBucket(entry.license)]++;
  }

  const total = entries.length || 1;
  return LICENSE_META.map((meta) => {
    const count = counts[meta.id];
    return {
      ...meta,
      count,
      pct: Math.round((count / total) * 100),
    };
  });
}

export function computeTopTasks(entries: Entry[], limit = 7): TaskDomainMetric[] {
  const map = new Map<string, number>();
  for (const entry of entries) {
    const task = entry.task?.trim();
    if (!task) continue;
    map.set(task, (map.get(task) ?? 0) + 1);
  }

  const total = entries.length || 1;
  return Array.from(map.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([task, count]) => ({
      task,
      count,
      pct: Math.round((count / total) * 100),
    }));
}

export function getTopFrontierModels(
  models: LeaderboardModel[],
  options?: {
    weights?: "All" | "Open" | "Proprietary";
    reasoningOnly?: boolean;
    limit?: number;
  },
): LeaderboardModel[] {
  const weights = options?.weights ?? "All";
  const reasoningOnly = options?.reasoningOnly ?? false;
  const limit = options?.limit ?? 6;

  const byRelease = new Map<string, LeaderboardModel>();
  for (const m of models) {
    if (m.deprecated) continue;
    if (m.intelligenceIndex === null || m.intelligenceIndex === undefined) continue;
    if (weights !== "All" && m.license !== weights) continue;
    if (reasoningOnly && !m.isReasoning) continue;

    const key = m.releaseSlug || m.releaseName || m.id;
    const prev = byRelease.get(key);
    if (!prev || (m.intelligenceIndex ?? 0) > (prev.intelligenceIndex ?? 0)) {
      byRelease.set(key, m);
    }
  }

  return Array.from(byRelease.values())
    .sort((a, b) => (b.intelligenceIndex ?? 0) - (a.intelligenceIndex ?? 0))
    .slice(0, limit);
}

export function searchCatalogQuickMatches(
  entries: Entry[],
  query: string,
  limit = 6,
): Entry[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return [];

  const scored: Array<{ entry: Entry; score: number }> = [];
  for (const entry of entries) {
    const name = entry.name.toLowerCase();
    const org = (entry.org || "").toLowerCase();
    const task = (entry.task || "").toLowerCase();
    const type = (entry.type || "").toLowerCase();
    const license = (entry.license || "").toLowerCase();
    const summary = (entry.summary || "").toLowerCase();

    let score = 0;
    if (name === trimmed) score += 100;
    else if (name.startsWith(trimmed)) score += 60;
    else if (name.includes(trimmed)) score += 35;

    if (org.includes(trimmed)) score += 20;
    if (task.includes(trimmed)) score += 12;
    if (type.includes(trimmed)) score += 10;
    if (license.includes(trimmed)) score += 8;
    if (summary.includes(trimmed)) score += 5;

    if (score > 0) {
      if (entry.popular) score += 4;
      if (entry.year >= 2026) score += 2;
      scored.push({ entry, score });
    }
  }

  scored.sort((a, b) => b.score - a.score || b.entry.year - a.entry.year);
  return scored.slice(0, limit).map((s) => s.entry);
}

export function loadRecentViewedNames(): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = window.localStorage.getItem(RECENT_VIEWS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((item): item is string => typeof item === "string" && item.trim().length > 0);
  } catch {
    return [];
  }
}

export function recordRecentViewedName(name: string): string[] {
  const clean = name.trim();
  if (!clean || typeof window === "undefined") return [];
  const existing = loadRecentViewedNames().filter((n) => n !== clean);
  const next = [clean, ...existing].slice(0, MAX_RECENT_VIEWS);
  try {
    window.localStorage.setItem(RECENT_VIEWS_KEY, JSON.stringify(next));
  } catch {
    // Ignore storage quota restrictions
  }
  return next;
}

export function formatRelativeTimestamp(iso?: string): string {
  if (!iso) return "Synced recently";
  const ts = new Date(iso).getTime();
  if (Number.isNaN(ts)) return "Synced recently";

  const diffMs = Date.now() - ts;
  if (diffMs < 0) {
    return new Date(ts).toLocaleDateString("en-US", { month: "short", day: "numeric" });
  }
  const mins = Math.floor(diffMs / 60000);
  if (mins < 60) return `${Math.max(1, mins)}m ago`;
  const hours = Math.floor(mins / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  if (days === 1) return "Yesterday";
  if (days < 7) return `${days}d ago`;
  return new Date(ts).toLocaleDateString("en-US", { month: "short", day: "numeric" });
}

export function decodeHtmlEntities(text: string): string {
  if (!text || !text.includes("&")) return text;
  return text
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&nbsp;/g, " ");
}
